public class Primitives {
    public static void main(String[] args) {
        // primitives are which cant be break further like integers, floating points, Character(char)
        int roll_no = 64;
        char letter = 'A';
        float marks = 45.23f;
        double largeDecimalNumbers = 456785.24356343;
        long longInteger = 908790387944325L;
        boolean bool = false;

        System.out.println(roll_no);
        System.out.println(letter);
        System.out.println(marks);
        System.out.println(largeDecimalNumbers);
        System.out.println(longInteger);
        System.out.println(bool);
        // Strings are not primitive
        String str = "Sandeep";
        System.out.println(str);

    }
}
